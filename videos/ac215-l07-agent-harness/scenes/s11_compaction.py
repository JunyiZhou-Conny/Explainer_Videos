def place(m, left=None, right=None, top=None, bottom=None, cx=None, cy=None):
    """Move m so the given edge / centre coordinate is where asked."""
    if left is not None:
        m.shift(RIGHT * (left - m.get_left()[0]))
    if right is not None:
        m.shift(RIGHT * (right - m.get_right()[0]))
    if cx is not None:
        m.set_x(cx)
    if top is not None:
        m.shift(UP * (top - m.get_top()[1]))
    if bottom is not None:
        m.shift(UP * (bottom - m.get_bottom()[1]))
    if cy is not None:
        m.set_y(cy)
    return m


def flash(mob, color: str = TURN, k: float = 1.15):
    return Indicate(mob, color=color, scale_factor=k)


def apart(a, b, gap: float = 0.06):
    """Assert that the bounding boxes of a and b are at least `gap` apart (no overlap)."""
    ok = (a.get_right()[0] + gap <= b.get_left()[0] or b.get_right()[0] + gap <= a.get_left()[0]
          or a.get_top()[1] + gap <= b.get_bottom()[1] or b.get_top()[1] + gap <= a.get_bottom()[1])
    assert ok, (a.get_corner(DOWN + LEFT), a.get_corner(UP + RIGHT), b.get_corner(DOWN + LEFT), b.get_corner(UP + RIGHT))


def inside(m, x0: float = -6.55, x1: float = 6.55, y0: float = -3.55, y1: float = 3.55):
    assert m.get_left()[0] >= x0 and m.get_right()[0] <= x1 and m.get_bottom()[1] >= y0 and m.get_top()[1] <= y1, \
        (m.get_corner(DOWN + LEFT), m.get_corner(UP + RIGHT))


def pulse(m, color: str, k: float = 1.1, run_time: float = 0.7, frame=None, width: float = 5.0):
    """Indicate's swell without its fill (S07): m grows and shrinks back while its frame's border
    glows `color`; a filled card keeps its text readable."""
    fr = frame
    for name in ("box", "frame"):
        if fr is None:
            fr = getattr(m, name, None)
    c0, w0 = fr.get_stroke_color(), fr.get_stroke_width()
    col = ManimColor(color)
    state = {"s": 1.0}

    def upd(mob, a):
        b = there_and_back(a)
        s_ = 1 + (k - 1) * b
        mob.scale(s_ / state["s"])
        state["s"] = s_
        fr.set_stroke(interpolate_color(c0, col, b), width=w0 + (width - w0) * b)

    return UpdateFromAlphaFunc(m, upd, run_time=run_time, rate_func=linear)


def bar_y(t, rows: int) -> float:
    return strip_top(rows) - t.bar_h / 2


def fit(scene, t, rows: int, keep=None, tags=(), run_time: float = 0.8):
    """resize(), with the title-bar tags riding along on the bar; the title (which frame_tags
    moved left) is lent out of t while resize() runs, so it keeps its x (S07's idiom)."""
    y = bar_y(t, rows)
    title, t.title = t.title, None
    try:
        resize(scene, t, rows, keep=keep, run_time=run_time,
               extra=[title.animate.set_y(y), *[m.animate.set_y(y) for m in tags]])
    finally:
        t.title = title


def feed(t, items):
    """(rows, anims, done): print `items` ((text, colour) pairs, one row each, cut at the row like
    Terminal.print) into terminal `t` as ANIMATIONS, so the capsule can be re-pinned in the same
    play (S08's helper): rows that scroll off fade in place (first 30%), the staying rows shift up
    (30-65%), the new rows fade in after. Call done() after the play."""
    texts = [(t._cut(s_), col) for s_, col in items]
    assert 0 < len(texts) <= t.rows, len(texts)
    overflow = max(0, len(t.lines) + len(texts) - t.rows)
    gone = list(t.lines.submobjects[:overflow])
    stay = list(t.lines.submobjects[overflow:])
    anims = [FadeOut(r, rate_func=squish_rate_func(smooth, 0.0, 0.3)) for r in gone]
    if overflow and stay:
        anims += [r.animate(rate_func=squish_rate_func(smooth, 0.3, 0.65)).shift(UP * t.pitch * overflow)
                  for r in stay]
    new = VGroup()
    for j, (s_, col) in enumerate(texts):
        ln = mono_line(s_, t.size, col)
        t._place(ln, len(stay) + j)
        new.add(ln)
    for ln in new:
        t.lines.add(ln)
    t0 = (0.6 if stay else 0.32) if overflow else 0.0
    for ln in new:
        anims.append(FadeIn(ln, rate_func=squish_rate_func(smooth, t0, 1.0)))

    def done():
        for r in gone:
            if r in t.lines.submobjects:
                t.lines.remove(r)
    return new, anims, done


def sub_glyphs(t, s: str, sub: str, occurrence: int = 0) -> VGroup:
    """The glyphs of `sub` inside a Text built from `s` (a Text keeps no glyphs for spaces)."""
    i = -1
    for _ in range(occurrence + 1):
        i = s.find(sub, i + 1)
    if i < 0:
        raise ValueError(f"{sub!r} not in {s!r}")
    a = len(s[:i].replace(" ", ""))
    return VGroup(*t.submobjects[a:a + len(sub.replace(" ", ""))])


def grey_text(t, s: str, sub: str, color: str = S.GREY):
    """Colour every `sub` inside a Text built from `s` GREY (masks, '…')."""
    for k in range(s.count(sub)):
        sub_glyphs(t, s, sub, k).set_color(color)
    return t


